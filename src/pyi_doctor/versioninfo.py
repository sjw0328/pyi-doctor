"""Windows version resource for PyInstaller's ``--version-file`` option.

Executables without version information are one of the commonly cited
factors in antivirus heuristics, so pyi-doctor always embeds one on Windows.
"""

from __future__ import annotations

from pathlib import Path

from .config import Project


def render_version_file(project: Project, *, file_description: str = "") -> str:
    v = project.windows_version
    ver_str = project.version
    strings = [
        ("CompanyName", project.display_publisher),
        ("FileDescription", file_description or project.description or project.name),
        ("FileVersion", ver_str),
        ("InternalName", project.name),
        ("LegalCopyright", project.copyright or ""),
        ("OriginalFilename", project.name + ".exe"),
        ("ProductName", project.name),
        ("ProductVersion", ver_str),
    ]
    body = ",\n".join(f"        StringStruct({k!r}, {val!r})" for k, val in strings)
    return f"""# UTF-8
# Generated by pyi-doctor
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={v!r},
    prodvers={v!r},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
{body}
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write_version_file(project: Project, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_version_file(project), encoding="utf-8")
    return path
