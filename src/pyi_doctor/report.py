"""Build report (JSON + Markdown) and the antivirus false-positive submission notes."""

from __future__ import annotations

import json
import platform
import sys
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from . import __version__

STATUSES = ("ok", "warning", "failed", "skipped")
_ICON = {"ok": "OK", "warning": "WARN", "failed": "FAIL", "skipped": "SKIP"}

FP_SUBMISSION_URL = "https://www.microsoft.com/en-us/wdsi/filesubmission"


@dataclass
class Step:
    name: str
    status: str
    message: str = ""
    seconds: float = 0.0
    data: Dict[str, Any] = field(default_factory=dict)


@dataclass
class Report:
    project: Dict[str, Any]
    steps: List[Step] = field(default_factory=list)
    artifacts: List[Dict[str, Any]] = field(default_factory=list)
    environment: Dict[str, str] = field(default_factory=dict)
    created: str = ""

    def __post_init__(self) -> None:
        if not self.created:
            self.created = datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
        if not self.environment:
            self.environment = environment_info()

    @property
    def ok(self) -> bool:
        return all(s.status != "failed" for s in self.steps)

    def step(self, name: str) -> Optional[Step]:
        for s in self.steps:
            if s.name == name:
                return s
        return None

    def to_dict(self) -> dict:
        d = asdict(self)
        d["ok"] = self.ok
        return d

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2, ensure_ascii=False, default=str)

    def to_markdown(self) -> str:
        p = self.project
        lines = [
            f"# Build report: {p.get('name')} {p.get('version')}",
            "",
            f"- Created: {self.created}",
            f"- Result: {'all steps completed' if self.ok else 'one or more steps failed'}",
            f"- Environment: {self.environment.get('platform')}, Python {self.environment.get('python')}, "
            f"PyInstaller {self.environment.get('pyinstaller')}, pyi-doctor {__version__}",
            "",
            "## Steps",
            "",
            "| Step | Status | Time | Detail |",
            "|---|---|---|---|",
        ]
        for s in self.steps:
            msg = s.message.replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {s.name} | {_ICON.get(s.status, s.status)} | {s.seconds:.1f}s | {msg} |")
        diag = self.step("diagnose")
        if diag and diag.data.get("results"):
            lines += ["", "## Antivirus false-positive risk factors", ""]
            lines.append("Score is a sum of common risk factors for comparing builds; it does not predict any product's verdict.")
            for r in diag.data["results"]:
                lines += ["", f"### {Path(r['path']).name}: {r['score']}/100 ({r['level']})", ""]
                lines.append(f"- SHA256: `{r['sha256']}`")
                lines.append(f"- Microsoft Defender scan: {r['defender']['status']} {r['defender'].get('detail', '')}".rstrip())
                for f in r["factors"]:
                    lines.append(f"- [{f['weight']}] {f['label']}: {f['advice']}")
                for n in r.get("notes", []):
                    lines.append(f"- note: {n}")
        smoke = self.step("smoke")
        if smoke and smoke.data.get("results"):
            lines += ["", "## Smoke test", ""]
            for r in smoke.data["results"]:
                lines.append(f"- {r['target']}: {r['status']} ({r['message']})")
                for tip in r.get("suggestions", []):
                    lines.append(f"  - {tip}")
        if self.artifacts:
            lines += ["", "## Artifacts", ""]
            for a in self.artifacts:
                lines.append(f"- {a['kind']}: `{Path(a['path']).name}`")
        lines += ["", "---", "Generated by pyi-doctor. Results are provided AS IS; verify them before distribution.", ""]
        return "\n".join(lines)


def environment_info() -> Dict[str, str]:
    try:
        from importlib.metadata import version

        pyi = version("pyinstaller")
    except Exception:
        pyi = "not installed"
    return {
        "platform": f"{platform.system()} {platform.release()} ({platform.machine()})",
        "python": platform.python_version(),
        "pyinstaller": pyi,
        "pyi_doctor": __version__,
        "executable_bits": "64" if sys.maxsize > 2**32 else "32",
    }


def submission_notes(project: Dict[str, Any], files: List[Dict[str, Any]], environment: Dict[str, str]) -> str:
    """Text to paste into a false-positive submission form. ``files``: dicts with name, size, sha256."""
    lines = [
        "False-positive report notes",
        "",
        f"Software: {project.get('name')} {project.get('version')}",
        f"Publisher: {project.get('publisher') or '(not set)'}",
    ]
    if project.get("website"):
        lines.append(f"Website / source code: {project['website']}")
    if project.get("description"):
        lines.append(f"Description: {project['description']}")
    lines += [
        f"Packaging: PyInstaller {environment.get('pyinstaller')} on Python {environment.get('python')} "
        f"({environment.get('platform')})",
        "",
        "Files:",
    ]
    for f in files:
        lines.append(f"- {f['name']} ({f['size']:,} bytes)")
        lines.append(f"  SHA256: {f['sha256']}")
    lines += [
        "",
        "The files are a Python application packaged with PyInstaller. Detections on such files are",
        "often attributed to the shared PyInstaller bootloader rather than to the application code.",
        "Please re-analyse the files listed above.",
        "",
        f"Microsoft submission page: {FP_SUBMISSION_URL}",
        "Other vendors have their own submission pages; attach the same file list and hashes.",
        "",
    ]
    return "\n".join(lines)
